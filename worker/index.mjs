async function getEbayAccessToken(env) {
  const config = getEbayConfig(env);
  const { clientId, clientSecret, apiBase, environment } = config;
  if (!clientId || !clientSecret) throw new Error("ebay_not_configured");
  const cacheKey = environment + ":" + clientId;
  const cached = EBAY_TOKEN_CACHE.get(cacheKey);
  if (cached && cached.expiresAt > Date.now() + 30_000) return cached.token;

  const auth = btoa(clientId + ":" + clientSecret);
  let response;
  try {
    response = await fetch(apiBase + "/identity/v1/oauth2/token", {
      method: "POST",
      headers: {
        "Authorization": "Basic " + auth,
        "Content-Type": "application/x-www-form-urlencoded",
        "Accept": "application/json"
      },
      body: "grant_type=client_credentials&scope=" + encodeURIComponent("https://api.ebay.com/oauth/api_scope"),
      // Let Fetch expose the upstream response instead of masking a redirect as a network failure.
      redirect: "manual",
      signal: AbortSignal.timeout(8000)
    });
  } catch (error) {
    throw new Error(error?.name === "TimeoutError" || error?.name === "AbortError"
      ? "ebay_oauth_network_timeout" : "ebay_oauth_network_error");
  }
  if (!response.ok) throw new Error("ebay_oauth_http_" + response.status);
  let data;
  try {
    data = await response.json();
  } catch {
    throw new Error("ebay_oauth_invalid_json");
  }
  if (typeof data.access_token !== "string" || !data.access_token || !Number.isFinite(Number(data.expires_in))) {
    throw new Error("ebay_token_invalid");
  }
  const expiresAt = Date.now() + Math.max(60, Number(data.expires_in) - 60) * 1000;
  EBAY_TOKEN_CACHE.set(cacheKey, { token: data.access_token, expiresAt });
  return data.access_token;
}

