      if (!["mobile_money", "bank", "cash", "other"].includes(method)) return json({ error: "wallet_method_invalid" }, 400);
      if (!Number.isFinite(amount) || amount <= 0 || amount > 1_000_000_000_000) return json({ error: "wallet_amount_invalid" }, 400);
